"""
Pydantic Schemas for AI-Powered Leak Detection, Signal Processing & Ingestion
"""
from pydantic import BaseModel, Field, ConfigDict
from typing import List, Optional, Dict, Any
from datetime import datetime


class SensorReadingCreate(BaseModel):
    sensor_id: str = Field(..., description="Unique hardware or virtual sensor ID")
    sensor_type: str = Field(..., description="acoustic, pressure, flow, ground_moisture, temperature, rover_acoustic")
    pipeline_segment_id: str = Field(..., description="Target pipeline segment ID")
    measurement_value: float = Field(..., description="Physical sensor measurement value")
    measurement_unit: str = Field(..., description="Unit of measurement: dB, bar, m3/h, %, degC")
    sampling_rate_hz: Optional[float] = Field(1.0, description="Sampling frequency in Hz")
    quality_indicator: Optional[str] = Field("EXCELLENT", description="EXCELLENT, GOOD, DEGRADED, FAULT")
    is_simulated: bool = Field(True, description="Strict simulation provenance flag")
    source: str = Field("VIRTUAL_SIMULATION_ENGINE", description="Provenance source")


class SensorReadingResponse(SensorReadingCreate):
    id: str
    created_at: datetime
    model_config = ConfigDict(from_attributes=True)


class SyntheticWaveformRequest(BaseModel):
    scenario: str = Field(
        "MODERATE_LEAK",
        description="NORMAL_FLOW, BACKGROUND_NOISE, MINOR_LEAK, MODERATE_LEAK, MAJOR_LEAK, PRESSURE_TRANSIENT, MECHANICAL_VIBRATION"
    )
    duration_seconds: float = Field(1.0, ge=0.1, le=5.0, description="Waveform duration in seconds")
    sampling_rate_hz: int = Field(8000, description="Sampling rate in Hz (default 8000)")
    noise_level: float = Field(0.15, ge=0.0, le=1.0, description="Gaussian noise ratio")
    pipe_material: str = Field("ductile_iron", description="ductile_iron, cast_iron, steel, pvc, hdpe")
    pipe_diameter_mm: int = Field(300, description="Nominal diameter in mm")
    is_simulated: bool = Field(True, description="Simulation provenance")


class AcousticFeatures(BaseModel):
    rms_amplitude: float
    peak_amplitude: float
    std_dev: float
    snr_db: float
    dominant_frequency_hz: float
    spectral_centroid_hz: float
    spectral_bandwidth_hz: float
    leak_band_energy_ratio: float
    short_time_energy: float


class SyntheticWaveformResponse(BaseModel):
    scenario: str
    sampling_rate_hz: int
    duration_seconds: float
    sample_count: int
    features: AcousticFeatures
    time_series_sample: List[float] = Field(..., description="Downsampled waveform points for UI plotting (e.g. 100 points)")
    fft_spectrum_sample: List[Dict[str, float]] = Field(..., description="Frequency spectrum points [{freq, magnitude}]")
    is_simulated: bool = True
    disclaimer: str = "Synthetic waveform generated by virtual acoustic physics model. Not actual field telemetry."


class LeakAnalyzeRequest(BaseModel):
    pipeline_segment_id: str
    acoustic_sensor_id: Optional[str] = None
    pressure_bar: Optional[float] = Field(None, description="Measured pressure in bar")
    expected_pressure_bar: Optional[float] = Field(4.5, description="Nominal baseline pressure")
    flow_rate_m3h: Optional[float] = Field(None, description="Measured flow rate in m3/h")
    expected_flow_m3h: Optional[float] = Field(50.0, description="Nominal baseline flow rate")
    ground_moisture_pct: Optional[float] = Field(None, description="Ground moisture % VWC")
    baseline_moisture_pct: Optional[float] = Field(15.0, description="Nominal soil moisture")
    soil_temp_c: Optional[float] = Field(18.0, description="Soil temperature in Celsius")
    acoustic_scenario: Optional[str] = Field("MODERATE_LEAK", description="Scenario to synthesize if raw waveform omitted")
    sensor_reliability: Optional[float] = Field(0.95, ge=0.0, le=1.0)
    is_simulated: bool = Field(True)


class LeakAnalyzeBatchRequest(BaseModel):
    requests: List[LeakAnalyzeRequest]


class AiDetectionResponse(BaseModel):
    id: str
    pipeline_segment_id: str
    anomaly_score: float = Field(..., description="Isolation Forest anomaly score [0.0 - 1.0]")
    classification: str = Field(..., description="NORMAL, LOW_LEAK_PROBABILITY, MEDIUM_LEAK_PROBABILITY, HIGH_LEAK_PROBABILITY")
    confidence: float = Field(..., description="Calibrated prediction probability [0.0 - 1.0]")
    risk_level: str = Field(..., description="LOW, MODERATE, HIGH, CRITICAL")
    estimated_loss_lph: float = Field(..., description="Estimated water loss in litres per hour")
    estimated_latitude: Optional[float] = None
    estimated_longitude: Optional[float] = None
    localization_uncertainty_m: Optional[float] = None
    localization_quality: str
    status: str
    contributing_features: Dict[str, float]
    risk_explanation: str
    model_version: str
    created_at: datetime
    is_simulated: bool = True
    source: str = "VIRTUAL_SIMULATION_ENGINE"
    model_config = ConfigDict(from_attributes=True)


class AiDetectionStatusUpdate(BaseModel):
    status: str = Field(..., description="VERIFIED_BY_OPERATOR, REJECTED, INSPECTION_DISPATCHED")
    operator_notes: Optional[str] = None


class AiModelMetrics(BaseModel):
    model_name: str
    model_type: str
    accuracy: float
    precision_macro: float
    recall_macro: float
    f1_macro: float
    evaluation_dataset_size: int
    train_test_split: str
    evaluated_at: str
    is_simulated: bool = True


class AiHealthResponse(BaseModel):
    status: str
    active_models: List[str]
    total_detections: int
    unreviewed_detections: int
    high_critical_count: int
    is_simulated: bool = True

"""
AQUA CREW — Virtual Simulation Device Adapter (Task 18)
Normalizes simulated sensor data generated by EPANET, WNTR, or synthetic rover physics.
Strictly ensures provenance is flagged as 'SIMULATED'.
"""
from datetime import datetime, timezone
from typing import Dict, Any
from app.services.iot.adapters.base_adapter import BaseSensorAdapter, NormalizedTelemetry


class VirtualSensorAdapter(BaseSensorAdapter):
    def __init__(self):
        super().__init__(expected_unit="any", min_range=-1e6, max_range=1e6)

    def normalize(self, raw_input: Dict[str, Any]) -> NormalizedTelemetry:
        raw_val = float(raw_input.get("value", 0.0))
        sensor_type = str(raw_input.get("sensor_type", "pressure"))
        unit = str(raw_input.get("unit", "bar"))

        ts_raw = raw_input.get("timestamp")
        if isinstance(ts_raw, str):
            try:
                ts = datetime.fromisoformat(ts_raw.replace("Z", "+00:00"))
            except Exception:
                ts = datetime.now(timezone.utc)
        elif isinstance(ts_raw, (int, float)):
            ts = datetime.fromtimestamp(ts_raw, tz=timezone.utc)
        else:
            ts = datetime.now(timezone.utc)

        return NormalizedTelemetry(
            device_id=str(raw_input.get("device_id", "DEV-VIRT-01")),
            sensor_id=str(raw_input.get("sensor_id", f"{raw_input.get('device_id', 'DEV-VIRT')}-{sensor_type[:2].upper()}")),
            sensor_type=sensor_type,
            measurement_value=raw_val,
            unit=unit,
            timestamp=ts,
            sequence_number=int(raw_input.get("seq", raw_input.get("sequence_number", 1))),
            raw_payload=raw_input,
            data_quality="VALID",
            provenance="SIMULATED",  # NEVER claim simulated data is MEASURED!
            firmware_version="v4.0.0-wntr-sim",
            calibration_reference=str(raw_input.get("calibration_reference", "TODINI_GGA_VERIFIED")),
            metadata={
                "simulation_model": str(raw_input.get("model", "EPANET_NET1")),
                "nodal_residual": float(raw_input.get("residual", 1e-6)),
            },
        )


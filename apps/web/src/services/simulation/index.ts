export async function fetchCommandCenterData(): Promise<CommandCenterDataBundle> {
  const [
    kpis,
    network,
    rovers,
    sensors,
    incidents,
    missions,
    alerts,
    analytics,
  ] = await Promise.all([
    fetchDashboardKpis(),
    fetchNetworkOverview(),
    fetchRovers(),
    fetchSensorCategories(),
    fetchIncidents(),
    fetchMissions(),
    fetchAlerts(),
    fetchAnalyticsTrends(),
  ]);

  return {
    kpis,
    network,
    rovers,
    sensors,
    incidents,
    missions,
    alerts,
    analytics,
    timestamp: new Date().toLocaleTimeString(),
  };
}
